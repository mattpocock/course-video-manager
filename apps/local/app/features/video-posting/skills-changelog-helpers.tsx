"use client";

import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { localImageRefs } from "@/features/image-upload/image-upload-job";
import { useImageUploadJob } from "@/features/image-upload/use-image-upload-job";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { Label } from "@/components/ui/label";
import {
  DropdownMenu,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { ActionMenuContent } from "@/features/action-menu/action-menu";
import { useConfirmDialog } from "@/features/action-menu/confirm-dialog";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { ImageIcon, Loader2Icon, SparklesIcon, Trash2Icon } from "lucide-react";
import type { CourseStructure } from "@/components/video-context-panel";
import type { SectionWithWordCount } from "@/features/article-writer/types";

export function ImageUploadDropdown({
  videoId,
  body,
  onBodyChange,
}: {
  videoId: string;
  body: string;
  onBodyChange: (body: string) => void;
}) {
  const { confirm, dialog: confirmDialog } = useConfirmDialog();
  const hasLocalImages = useMemo(() => localImageRefs(body).length > 0, [body]);
  // An `upload-images` Job: the URLs are swapped into the body as it is when
  // the Job settles, and a local file goes only once that body is saved. The
  // body is this tab's draft (local storage), so setting it is the save.
  const { isUploading, upload } = useImageUploadJob(videoId, {
    read: () => body,
    save: async (next) => onBodyChange(next),
  });
  const handleUpload = (deleteLocalFiles: boolean) => {
    if (!body.trim()) return;
    upload(deleteLocalFiles);
  };

  if (!hasLocalImages && !isUploading) return null;

  return (
    <>
      {confirmDialog}
      <DropdownMenu>
        <DropdownMenuTrigger asChild>
          <Button variant="outline" size="sm" disabled={isUploading}>
            {isUploading ? (
              <>
                <Loader2Icon className="h-4 w-4 animate-spin" />
                Uploading images...
              </>
            ) : (
              <>
                <ImageIcon className="h-4 w-4" />
                Upload Images to Cloudinary
              </>
            )}
          </Button>
        </DropdownMenuTrigger>
        <ActionMenuContent
          menu="dropdown"
          align="start"
          groups={{
            run: [
              {
                label: "Upload",
                icon: ImageIcon,
                description:
                  "Upload local images to Cloudinary and update references",
                onSelect: () => void handleUpload(false),
              },
            ],
            danger: [
              {
                label: "Upload and Delete Local Files",
                icon: Trash2Icon,
                description:
                  "Upload to Cloudinary, then remove the local image files",
                opensDialog: true,
                onSelect: () =>
                  confirm({
                    title: "Delete local image files?",
                    description:
                      "The images are uploaded to Cloudinary, then their local files are deleted. This cannot be undone.",
                    confirmLabel: "Upload and Delete",
                    onConfirm: () => void handleUpload(true),
                  }),
              },
            ],
          }}
        />
      </DropdownMenu>
    </>
  );
}

export function SeoDescriptionField({
  videoId,
  description,
  onDescriptionChange,
  autoGenerate,
  enabledFiles,
  enabledSections,
  includeTranscript,
  courseStructure,
  includeCourseStructure,
  chapters,
}: {
  videoId: string;
  description: string;
  onDescriptionChange: (d: string) => void;
  autoGenerate: boolean;
  enabledFiles: Set<string>;
  enabledSections: Set<string>;
  includeTranscript: boolean;
  courseStructure: CourseStructure | null;
  includeCourseStructure: boolean;
  chapters: SectionWithWordCount[];
}) {
  const [isGenerating, setIsGenerating] = useState(false);
  const hasAutoGenerated = useRef(false);
  const [confirmRegenerate, setConfirmRegenerate] = useState(false);
  const [pendingGenerated, setPendingGenerated] = useState("");

  const isDescriptionTooLong = description.length > 160;

  const generate = useCallback(async () => {
    setIsGenerating(true);
    try {
      const transcriptEnabled =
        chapters.length > 0 ? enabledSections.size > 0 : includeTranscript;

      const response = await fetch(`/api/videos/${videoId}/generate`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          mode: "seo-description",
          enabledFiles: Array.from(enabledFiles),
          includeTranscript: transcriptEnabled,
          enabledSections: Array.from(enabledSections),
          courseStructure:
            includeCourseStructure && courseStructure
              ? courseStructure
              : undefined,
        }),
      });

      if (!response.ok) {
        throw new Error("Failed to generate description");
      }

      const result = await response.json();
      return result.text as string;
    } finally {
      setIsGenerating(false);
    }
  }, [
    videoId,
    chapters.length,
    enabledSections,
    includeTranscript,
    enabledFiles,
    includeCourseStructure,
    courseStructure,
  ]);

  useEffect(() => {
    if (!hasAutoGenerated.current && !description.trim() && autoGenerate) {
      hasAutoGenerated.current = true;
      generate()
        .then((text) => {
          if (text) onDescriptionChange(text);
        })
        .catch(console.error);
    }
  }, []);

  const handleRegenerate = async () => {
    const text = await generate();
    if (!text) return;

    if (description.trim()) {
      setPendingGenerated(text);
      setConfirmRegenerate(true);
    } else {
      onDescriptionChange(text);
    }
  };

  return (
    <>
      <div className="space-y-2">
        <div className="flex items-center justify-between">
          <Label htmlFor="sc-description">SEO Description</Label>
          <Button
            variant="outline"
            size="sm"
            onClick={handleRegenerate}
            disabled={isGenerating}
          >
            {isGenerating ? (
              <>
                <Loader2Icon className="h-4 w-4 animate-spin" />
                Generating...
              </>
            ) : (
              <>
                <SparklesIcon className="h-4 w-4" />
                Regenerate
              </>
            )}
          </Button>
        </div>
        <Textarea
          id="sc-description"
          value={description}
          onChange={(e) => onDescriptionChange(e.target.value)}
          placeholder={
            isGenerating
              ? "Generating description..."
              : "SEO description (160 characters max)..."
          }
          className={`min-h-[80px] resize-y ${isDescriptionTooLong ? "border-red-500 focus-visible:ring-red-500" : ""}`}
        />
        <p
          className={`text-xs text-right ${isDescriptionTooLong ? "text-red-500" : "text-muted-foreground"}`}
        >
          {description.length}/160
        </p>
      </div>

      <Dialog
        open={confirmRegenerate}
        onOpenChange={(open) => {
          if (!open) {
            setConfirmRegenerate(false);
            setPendingGenerated("");
          }
        }}
      >
        <DialogContent>
          <DialogHeader>
            <DialogTitle>Replace description?</DialogTitle>
            <DialogDescription>
              The description field already has content. Do you want to replace
              it with the newly generated text?
            </DialogDescription>
          </DialogHeader>
          <DialogFooter>
            <Button
              variant="outline"
              onClick={() => {
                setConfirmRegenerate(false);
                setPendingGenerated("");
              }}
            >
              Cancel
            </Button>
            <Button
              onClick={() => {
                onDescriptionChange(pendingGenerated);
                setConfirmRegenerate(false);
                setPendingGenerated("");
              }}
            >
              Replace
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  );
}
