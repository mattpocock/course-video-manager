import type { EffectReducer } from "use-effect-reducer";
import { isDefaultShortTitle } from "@cvm/core/features/videos/short-title";
import type { PostedPlatforms } from "@/lib/short-status";
import { findYouTubeMetadataProblem } from "@/lib/youtube-metadata";
import { findConvertibleAiHeroUrls, replaceUrls } from "./convert-short-links";
import {
  createInitialGeneratedFieldState,
  generatedFieldReducer,
} from "./generated-field-reducer";
import type { CreatedShortLink, GenerateTextRequest } from "./posting-requests";

/**
 * The Shorts page modal, Add to Posting Queue (#2617): the Short's title
 * (renamed on blur), its YouTube description (stored on the Video, saved on
 * blur, generated once on open when blank), where it was already posted, when
 * it would go out, and the press that adds it to the Posting Queue the way
 * `cvm short post` does. It never starts a posting Job: the Sidecar posts the
 * Short at its Posting Slot. The Short is a prop that changes while the
 * portrait studio keeps the modal mounted, so it comes in on the events. See
 * docs/FRONTEND_STATE.md.
 */
export namespace shortsPostingReducer {
  export type Field = "description";

  /** `cvm short post`'s verdict for this Short, as the modal shows it. */
  export interface Verdict {
    verdict: "queued" | "refused";
    /** Why it is refused; null when it is (or would be) queued. */
    reason: string | null;
    /** When it goes out, UK wall-clock time; null when refused. */
    goesOutAt: string | null;
  }

  export interface State {
    /** The Short the modal is open for, or `null` while it is closed. */
    openVideoId: string | null;
    /** The Short's saved title: what a refused rename goes back to. */
    videoTitle: string;
    title: string;
    description: string;
    /** The description as the Video has it; null until it has loaded. */
    savedDescription: string | null;
    /** When the Short would go out, or why it would be refused. */
    verdict: Verdict | null;
    fields: generatedFieldReducer.State<Field>;
    /** The description was generated on open once already (once per mount). */
    autoGenerated: boolean;
    postedStatus: PostedPlatforms | null;
    /** Add to Posting Queue was pressed and has not answered yet. */
    adding: boolean;
    /** The description the short links are being made for. */
    convertingShortLinks: { description: string } | null;
  }

  export type Action =
    | generatedFieldReducer.Action<Field, GenerateTextRequest>
    | { type: "modal-opened"; videoId: string }
    | { type: "modal-closed" }
    | {
        type: "queue-preview-loaded";
        videoId: string;
        description: string;
        verdict: Verdict;
      }
    | { type: "queue-preview-failed"; videoId: string }
    | {
        type: "posted-status-loaded";
        videoId: string;
        postedStatus: PostedPlatforms;
      }
    /** The Short's title as the page has it, on open and after a reload. */
    | { type: "video-title-loaded"; videoTitle: string }
    | { type: "title-edited"; title: string }
    | { type: "title-blurred"; videoId: string }
    | { type: "short-renamed"; videoId: string }
    | { type: "rename-refused"; reason: "name-taken" | "failed" }
    | { type: "description-edited"; description: string }
    | { type: "description-blurred"; videoId: string }
    | { type: "description-saved"; videoId: string; description: string }
    | { type: "description-save-failed" }
    | { type: "add-to-queue-clicked"; videoId: string }
    | { type: "add-to-queue-answered"; videoId: string; verdict: Verdict }
    | { type: "add-to-queue-failed"; reason: "name-taken" | "failed" }
    | { type: "convert-short-links-clicked" }
    | { type: "short-links-created"; links: CreatedShortLink[] }
    | { type: "short-links-failed" };

  export type Effect =
    | { type: "generate-text"; field: Field; request: GenerateTextRequest }
    | { type: "load-posted-status"; videoId: string }
    | { type: "load-queue-preview"; videoId: string }
    | { type: "rename-short"; videoId: string; name: string }
    | { type: "save-description"; videoId: string; description: string }
    | {
        type: "add-to-posting-queue";
        videoId: string;
        title: string;
        description: string;
      }
    | { type: "close-modal" }
    /** Tell the page: its Queue panel and grid are out of date. */
    | { type: "report-queued"; videoId: string }
    | { type: "create-short-links"; urls: string[]; linkDescription: string }
    | { type: "show-toast"; title: string; description?: string }
    | { type: "show-error"; title: string };
}

export const createInitialShortsPostingState = (
  videoTitle: string
): shortsPostingReducer.State => ({
  openVideoId: null,
  videoTitle,
  title: videoTitle,
  description: "",
  savedDescription: null,
  verdict: null,
  fields: createInitialGeneratedFieldState(),
  autoGenerated: false,
  postedStatus: null,
  adding: false,
  convertingShortLinks: null,
});

/**
 * What YouTube would refuse, named, so the Short is never queued with it. A
 * blank title is reported elsewhere.
 */
export const selectMetadataProblem = (state: shortsPostingReducer.State) =>
  state.title.trim()
    ? findYouTubeMetadataProblem({
        title: state.title,
        description: state.description,
      })
    : null;

/** A Short's description is written from its transcript alone. */
export const selectDescriptionRequest = (
  videoId: string
): GenerateTextRequest => ({
  videoId,
  mode: "youtube-description",
  enabledFiles: [],
  includeTranscript: true,
  enabledSections: [],
});

/** Add to Posting Queue can be pressed. */
export const selectCanAdd = (state: shortsPostingReducer.State) =>
  state.savedDescription !== null &&
  !state.adding &&
  !!state.title.trim() &&
  !!state.description.trim() &&
  !selectMetadataProblem(state);

type State = shortsPostingReducer.State;
type Exec = (effect: shortsPostingReducer.Effect) => void;

/** A new description, from the model or the short links: shown and saved. */
const applyDescription = (
  state: State,
  description: string,
  exec: Exec
): State => {
  if (state.openVideoId !== null) {
    exec({
      type: "save-description",
      videoId: state.openVideoId,
      description: description.trim(),
    });
  }
  return { ...state, description };
};

const fieldAction = (
  state: State,
  action: generatedFieldReducer.Action<
    shortsPostingReducer.Field,
    GenerateTextRequest
  >,
  exec: Exec
): State => {
  if (
    action.type === "text-generation-failed" &&
    state.fields.generating?.field === action.field
  ) {
    exec({ type: "show-error", title: "Failed to generate text" });
  }
  // The description lives in this state, so an applied text lands here.
  const applied: string[] = [];
  const fields = generatedFieldReducer(state.fields, action, (effect) => {
    if (effect.type === "apply-field-text") applied.push(effect.text);
    else exec(effect);
  });
  const next = fields === state.fields ? state : { ...state, fields };
  const text = applied.at(-1);
  return text === undefined ? next : applyDescription(next, text, exec);
};

const previewLoaded = (
  state: State,
  action: Extract<
    shortsPostingReducer.Action,
    { type: "queue-preview-loaded" }
  >,
  exec: Exec
): State => {
  // A late answer, for a modal since closed or opened on another Short.
  if (action.videoId !== state.openVideoId) return state;
  if (state.savedDescription !== null) {
    return { ...state, verdict: action.verdict };
  }
  const loaded = {
    ...state,
    verdict: action.verdict,
    description: action.description,
    savedDescription: action.description,
  };
  if (state.autoGenerated || action.description.trim()) return loaded;
  return {
    ...fieldAction(
      loaded,
      {
        type: "generate-clicked",
        field: "description",
        currentText: action.description,
        askToReplace: false,
        request: selectDescriptionRequest(action.videoId),
      },
      exec
    ),
    autoGenerated: true,
  };
};

const addToQueueClicked = (
  state: State,
  videoId: string,
  exec: Exec
): State => {
  if (state.adding || state.savedDescription === null) return state;
  const title = state.title.trim();
  if (isDefaultShortTitle(title)) {
    exec({
      type: "show-error",
      title:
        "Rename this short before queueing it — it still has its default title.",
    });
    return state;
  }
  if (!state.description.trim()) {
    exec({ type: "show-error", title: "Description is required" });
    return state;
  }
  const problem = selectMetadataProblem(state);
  if (problem) {
    exec({ type: "show-error", title: problem.message });
    return state;
  }
  exec({
    type: "add-to-posting-queue",
    videoId,
    title,
    description: state.description.trim(),
  });
  return { ...state, adding: true };
};

const addToQueueAnswered = (
  state: State,
  verdict: shortsPostingReducer.Verdict,
  exec: Exec
): State => {
  if (!state.adding) return state;
  if (verdict.verdict === "refused") {
    exec({
      type: "show-error",
      title: `Not queued: ${verdict.reason ?? "refused"}`,
    });
    return { ...state, adding: false, verdict };
  }
  exec({ type: "close-modal" });
  if (state.openVideoId !== null) {
    exec({ type: "report-queued", videoId: state.openVideoId });
  }
  exec({
    type: "show-toast",
    title: "Added to the Posting Queue",
    description: `"${state.title.trim()}" goes out ${verdict.goesOutAt} (UK time)`,
  });
  return { ...state, adding: false, verdict };
};

const convertShortLinksClicked = (state: State, exec: Exec): State => {
  if (state.convertingShortLinks) return state;
  const urls = findConvertibleAiHeroUrls(state.description);
  if (urls.length === 0) {
    exec({
      type: "show-toast",
      title: "No convertible links",
      description: "No aihero.dev links to convert in the description.",
    });
    return state;
  }
  exec({
    type: "create-short-links",
    urls,
    linkDescription: `YouTube Short (${state.videoTitle})`,
  });
  return {
    ...state,
    convertingShortLinks: { description: state.description },
  };
};

const shortLinksCreated = (
  state: State,
  links: CreatedShortLink[],
  exec: Exec
): State => {
  const converting = state.convertingShortLinks;
  if (!converting) return state;
  const count = links.length;
  exec({
    type: "show-toast",
    title: "Links converted",
    description: `Converted ${count} aihero.dev URL${count > 1 ? "s" : ""} to short links.`,
  });
  return applyDescription(
    { ...state, convertingShortLinks: null },
    replaceUrls(
      converting.description,
      new Map(links.map((link) => [link.url, link.shortLinkUrl]))
    ),
    exec
  );
};

const descriptionBlurred = (
  state: State,
  videoId: string,
  exec: Exec
): State => {
  const description = state.description.trim();
  if (state.savedDescription === null || description === state.savedDescription)
    return state;
  exec({ type: "save-description", videoId, description });
  return state;
};

export const shortsPostingReducer: EffectReducer<
  shortsPostingReducer.State,
  shortsPostingReducer.Action,
  shortsPostingReducer.Effect
> = (state, action, exec) => {
  switch (action.type) {
    case "generate-clicked":
    case "text-generated":
    case "text-generation-failed":
    case "text-offered":
    case "overwrite-confirmed":
    case "overwrite-cancelled":
      return fieldAction(state, action, exec);
    case "modal-opened":
      exec({ type: "load-posted-status", videoId: action.videoId });
      exec({ type: "load-queue-preview", videoId: action.videoId });
      return { ...state, openVideoId: action.videoId };
    case "modal-closed":
      if (state.openVideoId === null) return state;
      // Reopening reads the Video afresh: the CLI may have changed it.
      return {
        ...state,
        openVideoId: null,
        savedDescription: null,
        verdict: null,
        postedStatus: null,
        adding: false,
      };
    case "queue-preview-loaded":
      return previewLoaded(state, action, exec);
    case "queue-preview-failed":
      if (action.videoId !== state.openVideoId) return state;
      exec({ type: "show-error", title: "Failed to load the Posting Queue" });
      return state;
    case "posted-status-loaded":
      if (action.videoId !== state.openVideoId) return state;
      return { ...state, postedStatus: action.postedStatus };
    case "video-title-loaded":
      return {
        ...state,
        videoTitle: action.videoTitle,
        title: action.videoTitle,
      };
    case "title-edited":
      return { ...state, title: action.title };
    case "title-blurred": {
      const name = state.title.trim();
      if (!name || name === state.videoTitle) return state;
      exec({ type: "rename-short", videoId: action.videoId, name });
      return state;
    }
    case "short-renamed":
      // A refusal may have been about the old title.
      if (action.videoId !== state.openVideoId) return state;
      exec({ type: "load-queue-preview", videoId: action.videoId });
      return state;
    case "rename-refused":
      exec({
        type: "show-error",
        title:
          action.reason === "name-taken"
            ? "That name is already taken in this lesson."
            : "Failed to rename short",
      });
      return { ...state, title: state.videoTitle };
    case "description-edited":
      return { ...state, description: action.description };
    case "description-blurred":
      return descriptionBlurred(state, action.videoId, exec);
    case "description-saved":
      // A refusal may have been about the missing description.
      if (action.videoId !== state.openVideoId) return state;
      exec({ type: "load-queue-preview", videoId: action.videoId });
      return { ...state, savedDescription: action.description };
    case "description-save-failed":
      exec({ type: "show-error", title: "Failed to save the description" });
      return state;
    case "add-to-queue-clicked":
      return addToQueueClicked(state, action.videoId, exec);
    case "add-to-queue-answered":
      if (action.videoId !== state.openVideoId) return state;
      return addToQueueAnswered(state, action.verdict, exec);
    case "add-to-queue-failed":
      if (!state.adding) return state;
      exec({
        type: "show-error",
        title:
          action.reason === "name-taken"
            ? "That name is already taken in this lesson."
            : "Failed to add the Short to the Posting Queue",
      });
      return { ...state, adding: false };
    case "convert-short-links-clicked":
      return convertShortLinksClicked(state, exec);
    case "short-links-created":
      return shortLinksCreated(state, action.links, exec);
    case "short-links-failed":
      if (!state.convertingShortLinks) return state;
      exec({ type: "show-error", title: "Failed to convert links" });
      return { ...state, convertingShortLinks: null };
  }
};
