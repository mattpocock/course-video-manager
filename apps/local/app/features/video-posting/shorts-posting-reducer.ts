import type { EffectReducer } from "use-effect-reducer";
import { isDefaultShortTitle } from "@cvm/core/features/videos/short-title";
import type { PostedPlatforms } from "@/lib/short-status";
import { findYouTubeMetadataProblem } from "@/lib/youtube-metadata";
import { findConvertibleAiHeroUrls, replaceUrls } from "./convert-short-links";
import {
  createInitialGeneratedFieldState,
  generatedFieldReducer,
} from "./generated-field-reducer";
import type { CreatedShortLink, GenerateTextRequest } from "./posting-requests";

export type ShortsPostingMode = "both" | "youtube" | "tiktok";

/**
 * The Shorts posting modal: the Short's title (renamed on blur), its YouTube
 * description (generated once on open when blank), where it was already
 * posted, and the press that checks for the vertical export and starts the
 * posting Jobs. The description is stored per Short by the modal, so events
 * carry it as it was when the user acted. The Short and the posting mode are
 * props that change while the portrait studio keeps the modal mounted, so
 * they come in on the events too. See docs/FRONTEND_STATE.md.
 */
export namespace shortsPostingReducer {
  export type Field = "description";

  /** What the posting Jobs need, fixed when Post Short was pressed. */
  export interface Post {
    videoId: string;
    mode: ShortsPostingMode;
    title: string;
    description: string;
  }

  export interface State {
    /** The Short the modal is open for, or `null` while it is closed. */
    openVideoId: string | null;
    /** The Short's saved title: what a refused rename goes back to. */
    videoTitle: string;
    title: string;
    fields: generatedFieldReducer.State<Field>;
    /** The description was generated on open once already (once per mount). */
    autoGenerated: boolean;
    postedStatus: PostedPlatforms | null;
    checkingExport: Post | null;
    /** The description the short links are being made for. */
    convertingShortLinks: { description: string } | null;
  }

  export type Action =
    | generatedFieldReducer.Action<Field, GenerateTextRequest>
    | {
        type: "modal-opened";
        videoId: string;
        mode: ShortsPostingMode;
        description: string;
      }
    | { type: "modal-closed" }
    | {
        type: "posted-status-loaded";
        videoId: string;
        postedStatus: PostedPlatforms;
      }
    /** The Short's title as the page has it, on open and after a reload. */
    | { type: "video-title-loaded"; videoTitle: string }
    | { type: "title-edited"; title: string }
    | { type: "title-blurred"; videoId: string }
    | { type: "rename-refused"; reason: "name-taken" | "failed" }
    | {
        type: "post-clicked";
        videoId: string;
        mode: ShortsPostingMode;
        description: string;
      }
    | { type: "vertical-export-checked"; exists: boolean }
    | { type: "vertical-export-check-failed" }
    | { type: "convert-short-links-clicked"; description: string }
    | { type: "short-links-created"; links: CreatedShortLink[] }
    | { type: "short-links-failed" };

  export type Effect =
    | generatedFieldReducer.Effect<Field, GenerateTextRequest>
    | { type: "load-posted-status"; videoId: string }
    | { type: "rename-short"; videoId: string; name: string }
    | { type: "check-vertical-export"; videoId: string }
    | {
        type: "start-short-posting";
        videoId: string;
        title: string;
        description: string;
        /** Queue the vertical export first and post behind it. */
        exportFirst: boolean;
        toYoutube: boolean;
        toBuffer: boolean;
      }
    | { type: "close-modal" }
    | { type: "create-short-links"; urls: string[]; linkDescription: string }
    | { type: "show-toast"; title: string; description?: string }
    | { type: "show-error"; title: string };
}

export const createInitialShortsPostingState = (
  videoTitle: string
): shortsPostingReducer.State => ({
  openVideoId: null,
  videoTitle,
  title: videoTitle,
  fields: createInitialGeneratedFieldState(),
  autoGenerated: false,
  postedStatus: null,
  checkingExport: null,
  convertingShortLinks: null,
});

/** The description only shows, and is only required, for a YouTube post. */
export const selectShowsDescription = (mode: ShortsPostingMode) =>
  mode === "both" || mode === "youtube";

/**
 * What YouTube would refuse, named, so the Short is never queued with it.
 * Only a YouTube post is held to it; a blank title is reported elsewhere.
 */
export const selectMetadataProblem = (
  state: shortsPostingReducer.State,
  mode: ShortsPostingMode,
  description: string
) =>
  selectShowsDescription(mode) && state.title.trim()
    ? findYouTubeMetadataProblem({ title: state.title, description })
    : null;

/** A Short's description is written from its transcript alone. */
export const selectDescriptionRequest = (
  videoId: string
): GenerateTextRequest => ({
  videoId,
  mode: "youtube-description",
  enabledFiles: [],
  includeTranscript: true,
  enabledSections: [],
});

const postTarget = (mode: ShortsPostingMode) =>
  mode === "youtube"
    ? "YouTube Shorts"
    : mode === "tiktok"
      ? "Buffer"
      : "YouTube Shorts + Buffer";

type Exec = (effect: shortsPostingReducer.Effect) => void;

const modalOpened = (
  state: shortsPostingReducer.State,
  action: Extract<shortsPostingReducer.Action, { type: "modal-opened" }>,
  exec: Exec
): shortsPostingReducer.State => {
  const opened = { ...state, openVideoId: action.videoId };
  exec({ type: "load-posted-status", videoId: action.videoId });
  if (
    state.autoGenerated ||
    !selectShowsDescription(action.mode) ||
    action.description.trim()
  ) {
    return opened;
  }
  const fields = generatedFieldReducer(
    state.fields,
    {
      type: "generate-clicked",
      field: "description",
      currentText: action.description,
      askToReplace: false,
      request: selectDescriptionRequest(action.videoId),
    },
    exec
  );
  return { ...opened, autoGenerated: true, fields };
};

const postClicked = (
  state: shortsPostingReducer.State,
  action: Extract<shortsPostingReducer.Action, { type: "post-clicked" }>,
  exec: Exec
): shortsPostingReducer.State => {
  if (state.checkingExport) return state;
  const title = state.title.trim();
  if (isDefaultShortTitle(title)) {
    exec({
      type: "show-error",
      title:
        "Rename this short before posting — it still has its default title.",
    });
    return state;
  }
  if (selectShowsDescription(action.mode) && !action.description.trim()) {
    exec({ type: "show-error", title: "Description is required" });
    return state;
  }
  const problem = selectMetadataProblem(state, action.mode, action.description);
  if (problem) {
    exec({ type: "show-error", title: problem.message });
    return state;
  }
  exec({ type: "check-vertical-export", videoId: action.videoId });
  return {
    ...state,
    checkingExport: {
      videoId: action.videoId,
      mode: action.mode,
      title,
      description: action.description.trim(),
    },
  };
};

const verticalExportChecked = (
  state: shortsPostingReducer.State,
  action: Extract<
    shortsPostingReducer.Action,
    { type: "vertical-export-checked" }
  >,
  exec: Exec
): shortsPostingReducer.State => {
  const post = state.checkingExport;
  if (!post) return state;
  exec({
    type: "start-short-posting",
    videoId: post.videoId,
    title: post.title,
    description: post.description,
    exportFirst: !action.exists,
    toYoutube: post.mode === "both" || post.mode === "youtube",
    toBuffer: post.mode === "both" || post.mode === "tiktok",
  });
  exec({ type: "close-modal" });
  exec(
    action.exists
      ? {
          type: "show-toast",
          title: `${postTarget(post.mode)} posting started`,
        }
      : {
          type: "show-toast",
          title: "Export + post started",
          description: `"${post.title}" will export first, then post`,
        }
  );
  return { ...state, checkingExport: null };
};

const convertShortLinksClicked = (
  state: shortsPostingReducer.State,
  action: Extract<
    shortsPostingReducer.Action,
    { type: "convert-short-links-clicked" }
  >,
  exec: Exec
): shortsPostingReducer.State => {
  if (state.convertingShortLinks) return state;
  const urls = findConvertibleAiHeroUrls(action.description);
  if (urls.length === 0) {
    exec({
      type: "show-toast",
      title: "No convertible links",
      description: "No aihero.dev links to convert in the description.",
    });
    return state;
  }
  exec({
    type: "create-short-links",
    urls,
    linkDescription: `YouTube Short (${state.videoTitle})`,
  });
  return {
    ...state,
    convertingShortLinks: { description: action.description },
  };
};

const shortLinksCreated = (
  state: shortsPostingReducer.State,
  action: Extract<shortsPostingReducer.Action, { type: "short-links-created" }>,
  exec: Exec
): shortsPostingReducer.State => {
  const converting = state.convertingShortLinks;
  if (!converting) return state;
  const count = action.links.length;
  exec({
    type: "apply-field-text",
    field: "description",
    text: replaceUrls(
      converting.description,
      new Map(action.links.map((link) => [link.url, link.shortLinkUrl]))
    ),
  });
  exec({
    type: "show-toast",
    title: "Links converted",
    description: `Converted ${count} aihero.dev URL${count > 1 ? "s" : ""} to short links.`,
  });
  return { ...state, convertingShortLinks: null };
};

export const shortsPostingReducer: EffectReducer<
  shortsPostingReducer.State,
  shortsPostingReducer.Action,
  shortsPostingReducer.Effect
> = (state, action, exec) => {
  switch (action.type) {
    case "generate-clicked":
    case "text-generated":
    case "text-generation-failed":
    case "text-offered":
    case "overwrite-confirmed":
    case "overwrite-cancelled": {
      if (
        action.type === "text-generation-failed" &&
        state.fields.generating?.field === action.field
      ) {
        exec({ type: "show-error", title: "Failed to generate text" });
      }
      const fields = generatedFieldReducer(state.fields, action, exec);
      return fields === state.fields ? state : { ...state, fields };
    }
    case "modal-opened":
      return modalOpened(state, action, exec);
    case "modal-closed":
      if (state.openVideoId === null) return state;
      return { ...state, openVideoId: null };
    case "posted-status-loaded":
      // A late answer, for a modal since closed or opened on another Short.
      if (action.videoId !== state.openVideoId) return state;
      return { ...state, postedStatus: action.postedStatus };
    case "video-title-loaded":
      return {
        ...state,
        videoTitle: action.videoTitle,
        title: action.videoTitle,
      };
    case "title-edited":
      return { ...state, title: action.title };
    case "title-blurred": {
      const name = state.title.trim();
      if (!name || name === state.videoTitle) return state;
      exec({ type: "rename-short", videoId: action.videoId, name });
      return state;
    }
    case "rename-refused":
      exec({
        type: "show-error",
        title:
          action.reason === "name-taken"
            ? "That name is already taken in this lesson."
            : "Failed to rename short",
      });
      return { ...state, title: state.videoTitle };
    case "post-clicked":
      return postClicked(state, action, exec);
    case "vertical-export-checked":
      return verticalExportChecked(state, action, exec);
    case "vertical-export-check-failed":
      if (!state.checkingExport) return state;
      exec({ type: "show-error", title: "Failed to check export status" });
      return { ...state, checkingExport: null };
    case "convert-short-links-clicked":
      return convertShortLinksClicked(state, action, exec);
    case "short-links-created":
      return shortLinksCreated(state, action, exec);
    case "short-links-failed":
      if (!state.convertingShortLinks) return state;
      exec({ type: "show-error", title: "Failed to convert links" });
      return { ...state, convertingShortLinks: null };
  }
};
